/**
 * <B> Function: PFC_DcmAverageFactor(PFC_T *pData)  </B>
 *
 * @brief Ratio between the true cycle-average inductor current and the mid-ON
 * sample, i.e. the conduction fraction (d1+d2).
 * @param Pointer to the data structure containing PFC related variables
 * @return correction factor in (0,1]
 * @example
 * <code>
 * factor = PFC_DcmAverageFactor(pData);
 * </code>
 */
static float PFC_DcmAverageFactor(PFC_T *pData)
{
    /* IL is sampled at mid-ON:
     *   CCM: the sample already equals the average IL           -> factor 1.
     *   DCM: the sample is ~Ipk/2, but the cycle-average is LOWER because the
     *        current idles at zero for part of the period:
     *          I_avg = (Ipk/2)*(d1+d2) = sample * (d1 / D_ideal),
     *        with d1 = the ON duty that produced this sample (dutyRatio - NOT
     *        piCurrent.output, which is only the trim once the duty
     *        feed-forward is enabled),
     *        D_ideal = (Vout-Vin)/Vout = boostDutyRatio, and
     *        (d1+d2) = d1/D_ideal < 1 in DCM.
     * Note d2 = d1*Vg/(Vo-Vg) assumes an ideal converter: the diode drop, DCR
     * and Rds_on all stretch the real demagnetising time slightly. */
    float factor = 1.0f;

    if (pData->boostDutyRatio > 0.0f)
    {
        factor = pData->dutyRatio / pData->boostDutyRatio;

        /* Losses/transients can push d1 past D_ideal; that must never inflate
         * the reading, so cap at unity. Under PFC_DCM_COMP_RATIO this cap is
         * also what decides CCM, which is precisely the weakness that
         * PFC_DCM_COMP_VALLEY_EST removes. */
        if (factor > 1.0f)
        {
            factor = 1.0f;
        }
        else if (factor < 0.0f)
        {
            factor = 0.0f;
        }
    }
    return factor;
}
/**
 * <B> Function: PFC_ConductionModeDetect(PFC_T *pData)  </B>
 *
 * @brief Detects CCM/DCM by predicting the inductor current at the end of the
 * OFF time and testing it against zero. Also publishes the estimate itself in
 * pData->iValleyEst for logging.
 * @param Pointer to the data structure containing PFC related variables
 * @return 1 if DCM, 0 if CCM
 * @example
 * <code>
 * pData->dcmDetected = PFC_ConductionModeDetect(pData);
 * </code>
 */
static uint16_t PFC_ConductionModeDetect(PFC_T *pData)
{
    const float d  = pData->dutyRatio;          /* duty that produced this sample */
    const float vg = pData->rectifiedVac;
    const float vo = pData->pfcVoltage.vdc;

    /* Walk the CCM current path forward from the mid-ON sample:
     *    rise over the remaining half of the ON time : +(vg/L)*(d*Ts/2)
     *    fall over the whole OFF time                : +((vg-vo)/L)*(1-d)*Ts
     * Collecting terms,
     *    iValleyEst = i + (Ts/L)*( vg*(1 - d/2) - vo*(1 - d) )
     *
     * In CCM the current really does follow that path, so the estimate is the
     * actual valley and is >= 0. In DCM the current hits zero before the OFF
     * time is up and then sits there, so the continued-slope estimate
     * undershoots into negative territory.
     *
     * The point of doing it this way is the threshold: it is a FIXED zero, not
     * a sampled quantity. Comparing an estimate against a sample (which is what
     * the min(d1/D_ideal,1) clamp effectively does) makes the decision jitter
     * on sample noise right at the boundary, and every toggle is a duty
     * discontinuity that shows up as input current distortion. */
    pData->iValleyEst = pData->iL
                      + (PFC_TS_OVER_L * ((vg * (1.0f - (0.5f * d)))
                                        - (vo * (1.0f - d))));

    return (pData->iValleyEst < 0.0f) ? 1u : 0u;
}
/**
 * <B> Function: PFC_CurrentSampleCorrection(PFC_T *pData)  </B>
 *
 * @brief Function to calculate average value of current in discontinuous
 * conduction mode. Writes averageCurrent, dcmDetected, iValleyEst and
 * sampleCorrFactor.
 * @param Pointer to the data structure containing PFC related variables
 * @return none
 * @example
 * <code>
 * PFC_CurrentSampleCorrection(PFC_T *pData);
 * </code>
 */
static void PFC_CurrentSampleCorrection(PFC_T *pData)
{
    /* Always evaluated, whichever method is driving the loop, so that one run
     * shows what valley estimation would have decided even when it is not the
     * active method. Costs a handful of flops. */
    const uint16_t dcmByValley = PFC_ConductionModeDetect(pData);

    switch (pData->sampleCorrectionEnable)
    {
        case PFC_DCM_COMP_RATIO:
            /* Legacy: the unity cap is the mode decision. Report DCM whenever
             * the cap did not bind, so dcmDetected is directly comparable
             * against the valley method's answer. */
            pData->sampleCorrFactor = PFC_DcmAverageFactor(pData);
            pData->dcmDetected = (pData->sampleCorrFactor < 1.0f) ? 1u : 0u;
            break;

        case PFC_DCM_COMP_VALLEY_EST:
            /* Detect first, then correct only if DCM was actually detected. */
            pData->dcmDetected = dcmByValley;
            pData->sampleCorrFactor = (dcmByValley != 0u)
                                    ? PFC_DcmAverageFactor(pData)
                                    : 1.0f;
            break;

        case PFC_DCM_COMP_OFF:
        default:
            pData->dcmDetected = 0u;
            pData->sampleCorrFactor = 1.0f;
            break;
    }

    pData->averageCurrent = pData->iL * pData->sampleCorrFactor;
}
/**
 * <B> Function: PFC_DutyFeedForward(PFC_T *pData)  </B>
 *
 * @brief Open-loop duty that delivers currentReference at the present
 * operating point, so the current PI only has to trim losses instead of
 * synthesising the whole (Vo-Vg)/Vo profile through its integrator.
 * @param Pointer to the data structure containing PFC related variables
 * @return feed-forward duty ratio in [0, PFC_MAX_DUTY]
 * @example
 * <code>
 * pData->dutyFF = PFC_DutyFeedForward(pData);
 * </code>
 */
static float PFC_DutyFeedForward(PFC_T *pData)
{
    /* CCM: the inductor volt-second balance fixes the duty independently of
     * the current, so the ideal boost ratio IS the feed-forward. */
    float ff = pData->boostDutyRatio;

    /* DCM: volt-second balance no longer pins the duty - the average current
     * is a static function of it,
     *      I_avg = (Ts*Vg*d^2) / (2L*D_ideal)
     * so the duty that open-loop delivers the reference is
     *      d = sqrt( (2L/Ts) * Iref * D_ideal / Vg ).
     * Substituting d = D_ideal shows the two branches meet exactly at the
     * CCM/DCM boundary, so switching between them introduces no step.
     * dcmDetected comes from PFC_CurrentSampleCorrection, which has already
     * run this cycle. */
    if (pData->dcmDetected != 0u)
    {
        /* Vg is floored, not tested: falling back to the CCM branch here would
         * be badly wrong, because at the zero crossing D_ideal -> 1 while the
         * demanded current is ~0 - that would command near-maximum duty into
         * the notch. Flooring instead keeps the expression finite and, since
         * currentReference is proportional to Vg, tapers ff smoothly to zero
         * as Vg does. Above the floor the result is exact. */
        float vg = pData->rectifiedVac;
        float arg;

        if (vg < PFC_DUTY_FF_VG_MIN)
        {
            vg = PFC_DUTY_FF_VG_MIN;
        }
        /* boostDutyRatio goes negative if Vg ever exceeds Vdc (sag, precharge),
         * which would make the argument negative. */
        arg = (PFC_TWO_L_OVER_TS * pData->currentReference
               * pData->boostDutyRatio) / vg;
        ff = (arg > 0.0f) ? sqrtf(arg) : 0.0f;
    }

    /* D_ideal exceeds PFC_MAX_DUTY either side of the zero crossing; the
     * converter simply cannot follow there, so cap rather than command a duty
     * the PWM will clip anyway. */
    if (ff > PFC_MAX_DUTY)
    {
        ff = PFC_MAX_DUTY;
    }
    else if (ff < 0.0f)
    {
        ff = 0.0f;
    }
    return ff;
}
/**
 * <B> Function: PFC_CurrentPILimitsUpdate(PFC_T *pData)  </B>
 *
 * @brief Set the current-PI output limits to match the ACTIVE duty
 * feed-forward mode. With the feed-forward on, the PI is a trim and the tight
 * symmetric bound doubles as its anti-windup; with it off (legacy) the PI
 * supplies the whole duty. Called from PFC_ParamsInit and again from
 * PFC_CurrentControlLoop whenever dutyFFEnable is toggled at run time -
 * setting the limits only at init left a run-time 1->0 toggle clamped at
 * +/-PFC_DUTY_TRIM_MAX, unable to reach the ~0.15..0.95 duty the boost needs.
 * @param Pointer to the data structure containing PFC related variables
 * @return none
 */
static void PFC_CurrentPILimitsUpdate(PFC_T *pData)
{
    if (pData->dutyFFEnable != 0u)
    {
        /* The PI is a trim on top of the feed-forward, so it must be able to
           go negative, and a tight symmetric bound is the anti-windup. */
        pData->piCurrent.maxOutput =  PFC_DUTY_TRIM_MAX;
        pData->piCurrent.minOutput = -PFC_DUTY_TRIM_MAX;
    }
    else
    {
        /* Legacy: the PI supplies the whole duty. */
        pData->piCurrent.maxOutput = PFC_MAX_DUTY;
        pData->piCurrent.minOutput = 0;
    }
}
/**
 * <B> Function: PFC_CurrentControlLoop(PFC_T *pData)  </B>
 *
 * @brief Function to execute current control loop of PFC
 * @param Pointer to the data structure containing PFC related variables
 * @return none
 * @example
 * <code>
 * PFC_CurrentControlLoop(PFC_T *pData);
 * </code>
 */
inline static void PFC_CurrentControlLoop(PFC_T *pData)
{
    float dutyRatio;
    float duty;

    /** Ensure PFC current  is not negative.*/
    if (pData->iL < 0)
    {
        pData->iL  = PFC_IL_MIN;
    }
    /** Calculate average current if converter operates in discontinuous
        conduction mode. In continuous conduction mode, measured current is
        used as is ,as average current is obtained. The method is selected by
        pData->sampleCorrectionEnable (PFC_DCM_COMP_T).
        NOTE: this consumes pData->dutyRatio, which still holds the duty that
        produced the present sample - it is only updated at the end of this
        function. */
    PFC_CurrentSampleCorrection(pData);

    /** dutyFFEnable is documented as run-time writable (X2C A/B testing).
        Detect a toggle, refresh the PI limits to match the new mode, and hand
        the operating point between the integrator and the feed-forward so the
        switch is approximately bumpless. The handover terms are estimates
        (last cycle's dutyFF, this cycle's boostDutyRatio - the DCM branch is
        lower); the trim clamp and the back-calculation below absorb the
        residual within a few cycles. */
    if (pData->dutyFFEnable != pData->dutyFFEnablePrev)
    {
        PFC_CurrentPILimitsUpdate(pData);
        if (pData->dutyFFEnable != 0u)
        {
            /* FF takes over ~D_ideal of the duty; remove it from the PI. */
            pData->piCurrent.integralOut -= pData->boostDutyRatio;
        }
        else
        {
            /* The PI must now supply what the FF was delivering. */
            pData->piCurrent.integralOut += pData->dutyFF;
        }
        pData->dutyFFEnablePrev = pData->dutyFFEnable;
    }

    /* Populate the reference/input fields for logging. The PI update only
     * consumes .error, so these are purely for a self-describing bus. */
    pData->piCurrent.reference = pData->currentReference;
    pData->piCurrent.input     = pData->averageCurrent;
    pData->piCurrent.error = (pData->currentReference - pData->averageCurrent);

    PFC_ControllerPIUpdate(&pData->piCurrent);

    /** Total duty = feed-forward + PI trim. With the feed-forward enabled the
        PI output is a small correction bounded by +/-PFC_DUTY_TRIM_MAX; with
        it disabled dutyFF is zero and the PI spans 0..PFC_MAX_DUTY as before
        (the limits are set to match in PFC_ParamsInit). */
    pData->dutyFF = (pData->dutyFFEnable != 0u) ? PFC_DutyFeedForward(pData)
                                                : 0.0f;
    dutyRatio = pData->dutyFF + pData->piCurrent.output;

    /** Clamp the SUM, and give the integrator back exactly what the clamp
        removed (back-calculation anti-windup). The previous code slammed
        integralOut to PI_I_OUT_MAX on saturation, which is wrong once the PI
        output is a trim - and even without the feed-forward it discarded the
        integrator state instead of holding it. */
    if (dutyRatio > PFC_MAX_DUTY)
    {
        pData->piCurrent.integralOut -= (dutyRatio - PFC_MAX_DUTY);
        dutyRatio = PFC_MAX_DUTY;
    }
    else if (dutyRatio < PFC_MIN_DUTY)
    {
        pData->piCurrent.integralOut += (PFC_MIN_DUTY - dutyRatio);
        dutyRatio = PFC_MIN_DUTY;
    }
    pData->dutyRatio = dutyRatio;

    /** Calculate duty cycle of PWM that controls PFC in terms of PWM Period */
    duty  = (dutyRatio * PFC_LOOPTIME_TCY);
    if (duty  > PFC_MAX_DUTY_COUNTS)
    {
        pData->duty = PFC_MAX_DUTY_COUNTS;
    }
    else if (duty  < PFC_MIN_DUTY_COUNTS)
    {
        pData->duty = PFC_MIN_DUTY_COUNTS;
    }
    else
    {
        pData->duty = duty;
    }
}
/**
 * <B> Function: PFC_CurrentRefGenerate(PFC_T *pData)  </B>
 * 
 * @brief Function to calculate current reference for the current control loop
 * @param Pointer to the data structure containing PFC related variables
 * @return none
 * @example
 * <code>
 * PFC_CurrentRefGenerate(PFC_T *pData);
 * </code>
 */
inline static void PFC_CurrentRefGenerate(PFC_T *pData)
{ 
    /** PI Execution - PFC output voltage control.
        Voltage PI is called at the rate specified by VOLTAGE_LOOP_EXE_RATE */
    if (++pData->voltLoopExeRate >= VOLTAGE_LOOP_EXE_RATE)
    {
        pData->piVoltage.error = pData->piVoltage.reference-pData->vdcFeedback;

        /* Gain-schedule the integral term with hysteresis: halve Ki for large
           errors, restore full Ki for small errors, and hold the current Ki
           inside the [LO, HI] band so it cannot dither at the switch point.
           piVoltage.ki persists across ticks, so no extra state is needed. */
        if((pData->piVoltage.error > PFC_VOLTAGE_ERR_GAIN_HI) ||
           (pData->piVoltage.error < -PFC_VOLTAGE_ERR_GAIN_HI))
        {
            pData->piVoltage.ki = KI_V / 2;
        }
        else if((pData->piVoltage.error < PFC_VOLTAGE_ERR_GAIN_LO) &&
                (pData->piVoltage.error > -PFC_VOLTAGE_ERR_GAIN_LO))
        {
            pData->piVoltage.ki = KI_V;
        }
        /* else: within the hysteresis band - hold the previous Ki. */
        /* Record the measurement for a self-describing bus; the reference is
         * already set by the soft-start ramp. */
        pData->piVoltage.input = pData->vdcFeedback;
        PFC_ControllerPIUpdate(&pData->piVoltage);
        pData->voltLoopExeRate = 0;
    }
    
    /** Current reference = powerCommand * rectifiedVac * KMUL / VacRMS^2.
        powerCommand is the voltage-loop output plus, when enabled, the load-
        power feed-forward (loadFF.powerFF). The feed-forward supplies the load
        power directly so the slow voltage loop only trims losses/errors; this
        cancels the load disturbance in the DC-bus power balance and sharply
        improves the load-step response. */
    {
        float powerCommand = pData->piVoltage.output;
        if (pData->loadFF.enable)
        {
            powerCommand += pData->loadFF.powerFF;
        }
        /* Published so burst control tests the real command - see
           PFC_BurstModeUpdate. */
        pData->powerCommand = powerCommand;
        pData->currentReference = (float)((powerCommand * pData->rectifiedVac * KMUL)
                            / pData->vacRMS.sqrOutput);
    }
    /**  Perform Boundary check of generated current reference */
    if (pData->currentReference > PFC_IREF_PEAK_MAX)
    {
        pData->currentReference = PFC_IREF_PEAK_MAX;
    }
    else if (pData->currentReference < 0)
    {
        pData->currentReference = 0;
    }
}
/**
 * <B> Function: float PFC_SignalRectification(PFC_MEASURE_VOLTAGE_T *pSignal)  </B>
 * 
 * @brief Function to rectify the input AC voltage
 * @param Pointer to the data structure containing measured voltage
 * @return Rectified signal
 * @example
 * <code>
 * PFC_SignalRectification();
 * </code>
 */
float PFC_SignalRectification(PFC_MEASURE_VOLTAGE_T *pSignal)
{   
    float output = pSignal->vac - pSignal->offsetVac;
    
    if(output < 0)
    {
        output = -(output);
    }  
    return(output);
}
/**
 * <B> Function: PFC_SquaredRMSCalculate(PFC_RMS_SQUARE_T *pData,float input)  </B>
 * 
 * @brief Function to calculate RMS value of an input signal
 * @param Pointer to the data structure containing variables related to RMS 
 * calculation, current value of signal  
 * @return none.
 * @example
 * <code>
 * PFC_SquaredRMSCalculate(PFC_RMS_SQUARE_T *pData,float input);
 * </code>
 */
static void PFC_SquaredRMSCalculate(PFC_RMS_SQUARE_T *pData,float input)
{       
        pData->sum += (float) (input*input);
    pData->samples++;
    /** Match PFC_Average's ordering: accumulate, increment, then test with >=
        so each window integrates exactly sampleLimit terms and divides by the
        same count. (Previously the sum held sampleLimit+1 terms but divided by
        sampleLimit, biasing sqrOutput high by 1/sampleLimit and stretching the
        window one sample past the half-line cycle.) */
    if(pData->samples >= pData->sampleLimit)
    {
       pData->sqrOutput = (float)((pData->sum/pData->sampleLimit));
       pData->status    = 1;
       pData->samples   = 0;
       pData->sum       = 0;
    }
}
/**
 * <B> Function: PFC_Average(PFC_AVG_T *pData,float input)  </B>
 * 
 * @brief Function to calculate moving average value of an input Signal
 * @param Pointer to the data structure containing variables related to average 
 * calculation, current value of signal 
 * @return none.
 * @example
 * <code>
 * PFC_Average(PFC_AVG_T *pData,float input);
 * </code>
 */
static void PFC_Average(PFC_AVG_T *pData,float input)
{
    pData->sum = pData->sum + input;
    pData->samples++;
    if(pData->samples >= pData->sampleLimit) 
    {
        pData->output  = (float)(pData->sum/pData->sampleLimit);
        pData->status  = 1;
        pData->sum     = 0;
        pData->samples = 0; 
    }
}


/**
 * <B> Function: PFC_FaultCheck(PFC_T *pData)  </B>
 * 
 * @brief Function to check the different fault status
 * @param Pointer to the data structure containing PFC related variables
 * @return none
 * @example
 * <code>
 * PFC_FaultCheck(PFC_T *pData);
 * </code>
 */
void PFC_FaultCheck(PFC_T *pData)
{
    /** Recompute the fault mask from scratch each pass so faults never
        accumulate or alias; each fault is an independent bit set with |=.
        Latching / recovery is handled by the PFC_FAULT state, not here. */
    uint16_t faults = PFC_FAULT_NONE;

    /*Check the condition for output over voltage*/
    if(pData->vdcAVG.output >= PFC_OUTPUT_OVER_VOLTAGE_LIMIT)
    {
        faults |= PFC_FAULT_OP_OV;
    }
    /*Check the condition for input under voltage*/
    if(pData->vacRMS.sqrOutput < PFC_INPUT_UNDER_VOLTAGE_LIMIT_LO)
    {
        faults |= PFC_FAULT_IP_UV;
    }
    /*Check the condition for input over voltage*/
    if(pData->vacRMS.sqrOutput >= PFC_INPUT_OVER_VOLTAGE_LIMIT_HI)
    {
        faults |= PFC_FAULT_IP_OV;
    }
    /** Instantaneous input over-current - software OCP on the offset-corrected
        inductor current (symmetric test catches either polarity). Latching:
        PFC_FAULT provides no auto-clear, because once PWM is disabled the
        inductor current decays to zero in microseconds and a threshold-based
        clear would self-clear immediately. */
    if((pData->iL >=  PFC_INPUT_OVER_CURRENT_PEAK) ||
       (pData->iL <= -PFC_INPUT_OVER_CURRENT_PEAK))
    {
        faults |= PFC_FAULT_IP_OC;
    }
    /** Output under-voltage (bus collapse / boost failure / overload), armed
        only once soft-start has reached the nominal reference - during the
        ramp the bus is legitimately below nominal. Auto-recovering with
        hysteresis (see the UV recovery clear in PFC_FAULT). */
    if((pData->piVoltage.reference >= PFC_OUPUT_VOLTAGE_REFERENCE) &&
       (pData->vdcAVG.output < PFC_OUTPUT_UNDER_VOLTAGE_LIMIT))
    {
        faults |= PFC_FAULT_OP_UV;
    }

    pData->faultStatus = faults;
}
