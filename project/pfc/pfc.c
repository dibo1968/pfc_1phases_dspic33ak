    pfcData->piCurrent.ki = KI_I;
    PFC_CurrentPILimitsUpdate(pfcData);
    pfcData->dutyFFEnablePrev = pfcData->dutyFFEnable;

/** Initialize PI controlling PFC Voltage Loop */    
